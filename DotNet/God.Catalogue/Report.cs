using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace God.Catalogue
{
    /// <summary>CATALOG-1: the coverage report (every row with its status). Deterministic: regenerates identically from catalogue.json.</summary>
    public static class Report
    {
        public const string Path = "docs/unification/catalogue/CATALOG1_REPORT.md";

        public static string Make(CatalogueDoc d, WareTable wares)
        {
            var sb = new StringBuilder();
            sb.Append("# CATALOG-1 coverage report\n\n");
            sb.Append("Generated by `God.Catalogue report` from `docs/unification/catalogue/catalogue.json` (UN3a). Do not edit by hand. Workbook SHA-256 `").Append(d.WorkbookSha256).Append("`; catalogue hash (canonical active rows) `")
              .Append(Generator.CatalogueHash(d)).Append("`.\n\n");

            // ---- summary ----
            sb.Append("## 1. Counts\n\n| Group | Rows | UA-initial | UB | Later | Superseded | implemented | staged | deferred | rejected |\n|---|---|---|---|---|---|---|---|---|---|\n");
            Counts(sb, "Controls", d.Controls.Cast<RowBase>());
            Counts(sb, "Needs", d.Needs.Cast<RowBase>());
            Counts(sb, "Objects", d.Objects.Cast<RowBase>());
            Counts(sb, "Buildings", d.Buildings.Cast<RowBase>());
            var ao = Rows.ActiveObjects(d).ToList(); var ab = Rows.ActiveBuildings(d).ToList();
            int recipes = ab.Sum(b => b.Def.Recipes.Count);
            int inter = ao.Sum(o => o.Def.Interactions.Count) + ab.Sum(b => b.Def.Interactions.Count);
            sb.Append("\nGenerated content: ").Append(ao.Count).Append(" object definitions (").Append(ao.Count(o => o.Stage == "UA-initial")).Append(" UA-initial plus ").Append(ao.Count(o => o.Stage != "UA-initial"))
              .Append(" endowment-only), ").Append(ab.Count).Append(" building definitions, ").Append(recipes).Append(" recipes, ").Append(inter).Append(" interaction rows. Ware ids requested for the UB rows: ")
              .Append(d.WareRequests.Count(w => !w.Reuse)).Append(" new (94-").Append(93 + d.WareRequests.Count(w => !w.Reuse)).Append("), ").Append(d.WareRequests.Count(w => w.Reuse)).Append(" reused.\n\n");

            // ---- needs ----
            sb.Append("## 2. Needs: active channels and relief rows\n\nAll 12 channels are active (default mask, design D9.4 d). Relief rows are the active catalogue rows whose effects relieve the channel.\n\n| # | Need | Channel | Workbook code status | UA relief rows | Other source |\n|---|---|---|---|---|---|\n");
            var cov = Audits.NeedCoverage(d, wares);
            foreach (var n in d.Needs)
                sb.Append("| ").Append(n.Id).Append(" | ").Append(n.Name).Append(" | ").Append(n.Channel).Append(" ").Append(UaContent.Channels[n.Channel]).Append(" | ").Append(n.Workbook["codeStatus"].Replace("|", "/")).Append(" | ")
                  .Append(cov[n.Channel].Count == 0 ? "none" : string.Join(", ", cov[n.Channel])).Append(" | ").Append(n.ReliefSource ?? "").Append(" |\n");
            sb.Append("\nSocial and Safety have no catalogue relief row by design: Social is relieved by gestures and shared play (a second person's actions), Safety by movement away from a threat.\n\n");

            // ---- production order ----
            Audits.Reachability(d, out var order);
            sb.Append("## 3. Computed production order of the UA content\n\nFrom the founder endowment, the environment (forage, water, herbs) and the six labour-only L1 shelters. Round 0 is the start; a step in round n needs only what rounds before n produced.\n\n");
            foreach (var g in order.GroupBy(s => s.Round))
            {
                sb.Append("Round ").Append(g.Key).Append(":\n\n");
                foreach (var s in g) sb.Append("- ").Append(s.Text).Append('\n');
                sb.Append('\n');
            }

            sb.Append("## 4. Unresolved bootstrap dependencies (outside UA by design)\n\n");
            foreach (var u in Audits.UnresolvedDependencies(d)) sb.Append("- ").Append(u).Append('\n');
            sb.Append("\nReed (Reed Yard, UB) and seeds (Seed plot, UB) are the only UB inputs that no UA row produces; sleeping mats need reed, so the founder hall carries them as an endowment (G6, G7). Mines and finite deposits are Later with no bootstrap path (G10). Meal, Ration and Snack stay Later (G12).\n\n");

            sb.Append("## 5. Ware ids requested for the lead (UN3a does not edit `Economy/Wares.cs`)\n\nAppend in this order (manifest order, append only). Rows marked reuse name an existing ware id of the same good; the lead confirms each reuse or assigns a new id.\n\n| Object | Name | Id | Note |\n|---|---|---|---|\n");
            foreach (var w in d.WareRequests)
                sb.Append("| ").Append(w.ObjectId).Append(" | ").Append(w.Name).Append(" | ").Append(w.ProposedId).Append(" | ").Append(w.Reuse ? "reuse existing `Ware." + w.ExistingWare + "`" : "new").Append(" |\n");

            sb.Append("\n## 6. Rows needing an owner or lead decision\n\n");
            foreach (var l in Decisions(d)) sb.Append("- ").Append(l).Append('\n');

            // ---- rows ----
            sb.Append("\n## 7. Controls\n\n| Id | Control | Prim | Status | Reason | Fix |\n|---|---|---|---|---|---|\n");
            foreach (var c in d.Controls) sb.Append("| ").Append(c.Id).Append(" | ").Append(c.Name).Append(" | ").Append(c.Prim).Append(" | ").Append(c.Status).Append(" | ").Append(c.Reason).Append(" | ").Append(string.Concat(c.Fix)).Append(" |\n");
            sb.Append("\n## 8. Objects\n\n| Id | CatId | WB row | Name | Stage | Status | Fix | Reason |\n|---|---|---|---|---|---|---|---|\n");
            foreach (var o in d.Objects) Row(sb, o);
            sb.Append("\n## 9. Buildings\n\n| Id | CatId | WB row | Name | Stage | Status | Fix | Reason |\n|---|---|---|---|---|---|---|---|\n");
            foreach (var b in d.Buildings) Row(sb, b);
            return sb.ToString();
        }

        static void Row(StringBuilder sb, RowBase r) =>
            sb.Append("| ").Append(r.Id).Append(" | ").Append(r.CatId).Append(" | ").Append(r.WorkbookRow).Append(" | ").Append(r.Name.Replace("|", "/")).Append(" | ").Append(r.Stage).Append(" | ").Append(r.Status).Append(" | ")
              .Append(string.Concat(r.Fix)).Append(" | ").Append(r.Reason.Replace("|", "/")).Append(" |\n");

        static void Counts(StringBuilder sb, string name, IEnumerable<RowBase> rows)
        {
            var l = rows.ToList();
            sb.Append("| ").Append(name).Append(" | ").Append(l.Count);
            foreach (var s in new[] { "UA-initial", "UB", "Later", "Superseded" }) sb.Append(" | ").Append(l.Count(r => r.Stage == s));
            foreach (var s in new[] { "implemented", "staged", "deferred", "rejected" }) sb.Append(" | ").Append(l.Count(r => r.Status == s));
            sb.Append(" |\n");
        }

        public static List<string> Decisions(CatalogueDoc d)
        {
            var l = new List<string>
            {
                "Effect argument meanings (catalogue.json `conventions`) are UN3a's defaults; UN1, UN3b, UN4 and UN8a confirm or request a change (the schema is frozen, so a change is a regenerate).",
                "Hall hearth: the hall has no WorkIn bin, so its cook row reads the inputs from the Storage bin (UN3b).",
                "OBJ-093 Sleeping mat stays stage UB (reed) but has an endowment-only definition so the hall's 12 mats can be installed and occupied (G6, G7); the lead may instead promote it in the manifest.",
                "Wetland has no terrain in the legacy `Terrain` enum: the clay shelter and clay raw use `Hills` until UN1 adds wetland.",
                "Fixture slots of the collection shelters (0/2/4) and the carpenter labour (300 ticks) are defaults not given by the workbook or D9.",
                "Empty-hand strike attack 1 is the generated constant `Catalogue.EmptyHandStrikeAttack` (the schema has no row for an unarmed strike); UN8a reads it.",
                "Ware ids 94-159 and the reuse of ten legacy ids (section 5) need a lead-run edit of `Economy/Wares.cs`.",
                "Settlement, Road, Seed plot, Reed Yard and every other UB row stay `staged`; TBD costs (Settlement, Road, upgrades, Ax Workshop and the like) stay inactive until the owner or UN7 sets them (F, G11).",
                "Mines, deposits and metals are `deferred` with no bootstrap path (G10); weapons and armour beyond the stone tools are Later (H, G4).",
            };
            return l;
        }
    }
}

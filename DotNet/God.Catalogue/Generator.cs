using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;

namespace God.Catalogue
{
    /// <summary>
    /// <c>generate</c>: catalogue.json to the deterministic C# tables (partials of the UN0 Catalogue facade) and catalogue.csv. No
    /// timestamps, fixed ordering by CatId, LF line endings, invariant culture. Returns path (relative to the repository root) to text.
    /// </summary>
    public static class Generator
    {
        public const string GeneratedDir = "Assets/God/Sim/Unified/Catalogue/Generated/";
        public const string CsvPath = "docs/unification/catalogue/catalogue.csv";

        public static Dictionary<string, string> Generate(CatalogueDoc doc, WareTable wares)
        {
            var files = new Dictionary<string, string>();
            string hash = CatalogueHash(doc);
            files[GeneratedDir + "Catalogue.Objects.g.cs"] = Objects(doc, wares);
            files[GeneratedDir + "Catalogue.Buildings.g.cs"] = Buildings(doc, wares);
            files[GeneratedDir + "Catalogue.Index.g.cs"] = Index(doc, wares, hash);
            files[GeneratedDir + "UnifiedWares.Weights.g.cs"] = Weights(doc, wares);
            files[CsvPath] = Csv(doc);
            return files;
        }

        // ---------- the hash of the canonical active rows ----------

        /// <summary>The canonical JSON of the active rows: sorted by CatId, compact, no wording (reason, workbook text), so a rewording does not change the hash.</summary>
        public static string CanonicalActiveJson(CatalogueDoc doc)
        {
            var list = new List<object>();
            foreach (var o in Rows.ActiveObjects(doc)) list.Add(new { o.Id, o.CatId, o.Stage, o.Fix, o.FixApplied, o.Def });
            foreach (var b in Rows.ActiveBuildings(doc)) list.Add(new { b.Id, b.CatId, b.Stage, b.Fix, b.FixApplied, b.Def });
            return JsonSerializer.Serialize(list, Store.Compact);
        }

        public static string CatalogueHash(CatalogueDoc doc) => Workbook.Hex(SHA256.HashData(Encoding.UTF8.GetBytes(CanonicalActiveJson(doc))));

        // ---------- emitters ----------
        static string N(int v) => v.ToString(CultureInfo.InvariantCulture);

        static string Header() =>
            "// <auto-generated>\n// UN3a: generated by DotNet/God.Catalogue from docs/unification/catalogue/catalogue.json. Do not edit; run `God.Catalogue generate`.\n" +
            "// Deterministic: no timestamp, fixed order by CatId, LF line endings.\n// </auto-generated>\n";

        static string ArgText(object arg, ArgType t, CatalogueDoc doc, WareTable wares)
        {
            if (!Spec.Resolve(arg, t, doc, wares, out int v, out string err)) throw new InvalidOperationException("argument: " + err);
            if (t == ArgType.Ware || (t == ArgType.WareOrZero && v != 0)) return "(short)Ware." + WareName(wares, v);
            return "(short)" + N(v);
        }

        static string WareName(WareTable wares, int id) => wares.Ids.First(kv => kv.Value == id).Key;

        static string Effect(EffectData e, CatalogueDoc doc, WareTable wares)
        {
            var spec = Spec.ArgTypes(e.Kind) ?? throw new InvalidOperationException("effect kind " + e.Kind);
            return "new EffectDef(EffectKind." + e.Kind + ", " + ArgText(e.A, spec[0], doc, wares) + ", " + ArgText(e.B, spec[1], doc, wares) + ", " + ArgText(e.C, spec[2], doc, wares) + ")";
        }

        static string Interaction(InteractionData i, CatalogueDoc doc, WareTable wares, string indent)
        {
            int cat = i.TargetCat == null ? 0 : Spec.CatOf(doc, i.TargetCat);
            string src;
            if (i.Source == "Ware") { src = "(int)Ware." + (string)Str(i.SourceArg); }
            else if (i.Source == "Tool" || i.Source == "Class") { src = N(Spec.CatOf(doc, (string)Str(i.SourceArg))); }
            else src = "0";
            var sb = new StringBuilder();
            sb.Append(indent).Append("new InteractionDef(TargetKind.").Append(i.Target).Append(", ").Append(N(cat)).Append(", ").Append(N(i.Slot)).Append(", SourceReq.").Append(i.Source)
              .Append(", ").Append(src).Append(", ").Append(N(i.Reach)).Append(", ").Append(N(i.Ticks));
            foreach (var e in i.Effects) sb.Append(",\n").Append(indent).Append("    ").Append(Effect(e, doc, wares));
            sb.Append(")");
            return sb.ToString();
        }

        public static string Str(object o) => o is JsonElement je ? (je.ValueKind == JsonValueKind.String ? je.GetString() : je.GetRawText()) : o?.ToString();

        static string Objects(CatalogueDoc doc, WareTable wares)
        {
            var sb = new StringBuilder(Header());
            sb.Append("\nnamespace God.Sim.Unified\n{\n    public static partial class Catalogue\n    {\n");
            sb.Append("        static partial void ObjectsUN3a(ref ObjectDef[] table)\n        {\n            table = new ObjectDef[]\n            {\n");
            foreach (var o in Rows.ActiveObjects(doc))
            {
                var d = o.Def;
                bool unique = wares.Unique.Contains(d.Ware);
                sb.Append("                // ").Append(o.Id).Append(' ').Append(o.Name).Append(o.Def.EndowmentOnly ? " (endowment only)" : "").Append('\n');
                sb.Append("                new ObjectDef(").Append(N(o.CatId)).Append(", Ware.").Append(d.Ware).Append(", ").Append(unique ? "true" : "false").Append(", ")
                  .Append(N(d.Weight)).Append(", ").Append(N(d.Nutrition)).Append(", ").Append(N(d.StrikeAttack)).Append(", ").Append(N(d.Defence)).Append(",\n");
                sb.Append("                    new ToolMul[] { ");
                sb.Append(string.Join(", ", d.ToolMultipliers.Select(t => "new ToolMul(EffectKind." + t.Effect + ", " + N(t.Permille) + ")")));
                sb.Append(" },\n                    new InteractionDef[]\n                    {\n");
                for (int k = 0; k < d.Interactions.Count; k++)
                    sb.Append(Interaction(d.Interactions[k], doc, wares, "                        ")).Append(k + 1 < d.Interactions.Count ? ",\n" : "\n");
                sb.Append("                    }),\n");
            }
            sb.Append("            };\n        }\n    }\n}\n");
            return sb.ToString();
        }

        static string Quantities(List<WareQtyData> l) => "new WareQty[] { " + string.Join(", ", l.Select(q => "new WareQty(Ware." + q.Ware + ", " + N(q.Count) + ")")) + " }";

        static string Buildings(CatalogueDoc doc, WareTable wares)
        {
            var sb = new StringBuilder(Header());
            sb.Append("\nnamespace God.Sim.Unified\n{\n    public static partial class Catalogue\n    {\n");
            sb.Append("        static partial void BuildingsUN3a(ref BuildingDef[] table)\n        {\n            table = new BuildingDef[]\n            {\n");
            foreach (var b in Rows.ActiveBuildings(doc))
            {
                var d = b.Def;
                sb.Append("                // ").Append(b.Id).Append(' ').Append(b.Name).Append('\n');
                sb.Append("                new BuildingDef(").Append(N(b.CatId)).Append(",\n                    new BuildingLevelDef[]\n                    {\n");
                foreach (var l in d.Levels)
                    sb.Append("                        new BuildingLevelDef(").Append(N(l.Labour)).Append(", ").Append(Quantities(l.Materials)).Append(", ").Append(N(l.Storage)).Append(", ")
                      .Append(N(l.SleepSpots)).Append(", ").Append(N(l.FixtureSlots)).Append(", ").Append(l.CollectWare == null ? "Ware.None" : "Ware." + l.CollectWare).Append(", ").Append(N(l.CollectRadius)).Append("),\n");
                string arg = d.PlacementArg == null ? "0" : N(wares.Terrains[d.PlacementArg]) + " /* Terrain." + d.PlacementArg + " */";
                sb.Append("                    },\n                    PlacementRule.").Append(d.Placement).Append(", ").Append(arg).Append(",\n");
                sb.Append("                    ").Append(d.Capabilities.Count == 0 ? "Capabilities.None" : string.Join(" | ", d.Capabilities.Select(c => "Capabilities." + c))).Append(",\n");
                sb.Append("                    new InteractionDef[]\n                    {\n");
                for (int k = 0; k < d.Interactions.Count; k++)
                    sb.Append(Interaction(d.Interactions[k], doc, wares, "                        ")).Append(k + 1 < d.Interactions.Count ? ",\n" : "\n");
                sb.Append("                    },\n                    new RecipeDef[]\n                    {\n");
                foreach (var r in d.Recipes)
                    sb.Append("                        new RecipeDef(").Append(N(r.Id)).Append(", ").Append(N(b.CatId)).Append(", ").Append(Quantities(r.Inputs)).Append(", ").Append(Quantities(r.Outputs))
                      .Append(", ").Append(N(r.LabourTicks)).Append(", ").Append(N(r.ToolBonus)).Append("), // ").Append(r.Name).Append('\n');
                sb.Append("                    }),\n");
            }
            sb.Append("            };\n        }\n    }\n}\n");
            return sb.ToString();
        }

        static string Index(CatalogueDoc doc, WareTable wares, string hash)
        {
            var sb = new StringBuilder(Header());
            sb.Append("\nnamespace God.Sim.Unified\n{\n    public static partial class Catalogue\n    {\n");
            sb.Append("        /// <summary>The SHA-256 of the canonical active-row JSON (catalogue.json, rows sorted by CatId); recorded by UN6t's artifact header.</summary>\n");
            sb.Append("        public const string CatalogueHash = \"").Append(hash).Append("\";\n\n");
            sb.Append("        /// <summary>The strike attack of an empty hand (D9.5 E); held objects carry their own <c>ObjectDef.StrikeAttack</c>.</summary>\n");
            sb.Append("        public const int EmptyHandStrikeAttack = 1;\n\n");
            sb.Append("        static partial void ShaUN3a(ref string sha) { sha = \"").Append(doc.WorkbookSha256).Append("\"; }\n\n");
            sb.Append("        static partial void RecipesUN3a(ref RecipeDef[] table)\n        {\n");
            sb.Append("            int n = 0;\n            for (int i = 0; i < Buildings.Count; i++) n += Buildings[i].Recipes.Count;\n");
            sb.Append("            var t = new RecipeDef[n];\n            n = 0;\n");
            sb.Append("            for (int i = 0; i < Buildings.Count; i++) for (int k = 0; k < Buildings[i].Recipes.Count; k++) t[n++] = Buildings[i].Recipes[k];\n");
            sb.Append("            System.Array.Sort(t, (a, b) => a.Id.CompareTo(b.Id));\n            table = t;\n        }\n\n");
            foreach (var kind in new[] { "Object", "Building" })
            {
                var aliases = new List<KeyValuePair<string, int>>();
                foreach (var r in kind == "Object" ? doc.Objects.Cast<RowBase>() : doc.Buildings.Cast<RowBase>())
                {
                    aliases.Add(new KeyValuePair<string, int>(r.Name.ToLowerInvariant(), r.CatId));
                    foreach (var a in r.Aliases) aliases.Add(new KeyValuePair<string, int>(a.ToLowerInvariant(), r.CatId));
                }
                aliases.Sort((x, y) => string.CompareOrdinal(x.Key, y.Key));
                sb.Append("        /// <summary>Lower-case ").Append(kind.ToLowerInvariant()).Append(" names and aliases, sorted ordinal; binary-searched by <see cref=\"").Append(kind).Append("IdOfName\"/>.</summary>\n");
                sb.Append("        private static readonly string[] ").Append(kind).Append("Keys = new string[]\n        {\n");
                foreach (var a in aliases) sb.Append("            \"").Append(a.Key.Replace("\\", "\\\\").Replace("\"", "\\\"")).Append("\",\n");
                sb.Append("        };\n\n        private static readonly ushort[] ").Append(kind).Append("Ids = new ushort[]\n        {\n");
                for (int i = 0; i < aliases.Count; i += 12)
                    sb.Append("            ").Append(string.Join(", ", aliases.Skip(i).Take(12).Select(a => N(a.Value)))).Append(",\n");
                sb.Append("        };\n\n");
                sb.Append("        /// <summary>The CatId of a ").Append(kind.ToLowerInvariant()).Append(" name or alias (lower case, as written in the catalogue), or <see cref=\"CatId.None\"/>. Binary search, no allocation.</summary>\n");
                sb.Append("        public static ushort ").Append(kind).Append("IdOfName(string lowerName)\n        {\n");
                sb.Append("            int lo = 0, hi = ").Append(kind).Append("Keys.Length - 1;\n");
                sb.Append("            while (lo <= hi) { int mid = (lo + hi) >> 1; int c = string.CompareOrdinal(").Append(kind).Append("Keys[mid], lowerName); if (c == 0) return ").Append(kind).Append("Ids[mid]; if (c < 0) lo = mid + 1; else hi = mid - 1; }\n");
                sb.Append("            return CatId.None;\n        }\n\n");
            }
            sb.Append("    }\n}\n");
            return sb.ToString();
        }

        static string Weights(CatalogueDoc doc, WareTable wares)
        {
            var sb = new StringBuilder(Header());
            sb.Append("\nnamespace God.Sim.Unified\n{\n    public static partial class UnifiedWares\n    {\n");
            sb.Append("        static partial void WeightUN3a(Ware w, ref int weight)\n        {\n            switch (w)\n            {\n");
            foreach (var o in Rows.ActiveObjects(doc).Where(o => wares.Id(o.Def.Ware) >= 72 && wares.Id(o.Def.Ware) <= 159).OrderBy(o => wares.Id(o.Def.Ware)))
                sb.Append("                case Ware.").Append(o.Def.Ware).Append(": weight = ").Append(N(o.Def.Weight)).Append("; break;\n");
            sb.Append("            }\n        }\n    }\n}\n");
            return sb.ToString();
        }

        static string Csv(CatalogueDoc doc)
        {
            var sb = new StringBuilder("id,cat_id,name,kind,stage,status,fix\n");
            foreach (var o in doc.Objects) sb.Append(Line(o, "object"));
            foreach (var b in doc.Buildings) sb.Append(Line(b, "building"));
            return sb.ToString();
        }

        static string Line(RowBase r, string kind) =>
            r.Id + "," + N(r.CatId) + "," + Quote(r.Name) + "," + kind + "," + r.Stage + "," + r.Status + "," + string.Join("", r.Fix) + "\n";

        static string Quote(string s) => s.Contains(",") || s.Contains("\"") ? "\"" + s.Replace("\"", "\"\"") + "\"" : s;
    }
}

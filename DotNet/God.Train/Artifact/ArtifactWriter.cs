using System;
using System.Collections.Generic;
using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;
using God.Sim.Unified;
using God.Train.Net;

namespace God.Train.Artifact
{
    /// <summary>
    /// The artifact header (the UN6 loader contract proposed in the UN6t-a thresholds commit message; UN6t-a spec 5.8): every field
    /// is a constant of the generated class <c>God.Sim.Unified.FounderPolicyV&lt;n&gt;</c>.
    /// </summary>
    public sealed class ArtifactHeader
    {
        public int Version = 1;
        /// <summary>"TRAINED", "FAILED-TR01", "INTERIM" or "SELF-TEST".</summary>
        public string Status = "SELF-TEST";
        public int ObsSchemaVersion = ObsSchema.Version;
        public string ObsSchemaHash = ObsSchema.SchemaHash;
        public int ActSchemaVersion = ActSchema.Version;
        public string ActSchemaHash = ActSchema.SchemaHash;
        public string CatalogueHash = "";
        public string TuningHash = "";
        public string CurriculumId = "";
        public string StagesTrained = "";
        public string StagesNotTrained = "";
        public string TrainingSeeds = "";
        public string TrainerCommit = "";
        public string ThresholdsHash = "";
        public string TrainingMetricsJson = "{}";
        public string NetShape = "";
        public int WeightScaleShift = QNet.WeightShift;
        public int WeightCount;
        public string WeightsSha256 = "";

        public static readonly string[] StringFields = { "Status", "ObsSchemaHash", "ActSchemaHash", "CatalogueHash", "TuningHash", "CurriculumId", "StagesTrained", "StagesNotTrained", "TrainingSeeds", "TrainerCommit", "ThresholdsHash", "TrainingMetricsJson", "NetShape", "WeightsSha256" };
        public static readonly string[] IntFields = { "Version", "ObsSchemaVersion", "ActSchemaVersion", "WeightScaleShift", "WeightCount" };
    }

    /// <summary>
    /// Writes and reads <c>Unified/Brain/Artifacts/FounderPolicyV&lt;n&gt;.g.cs</c>: the header constants and the int16 weights as
    /// base64 of their little-endian bytes, split into string chunks of at most <see cref="ChunkChars"/> characters. The text
    /// depends only on its inputs (no time stamp, "\n" line ends), so the same inputs give byte-identical files.
    /// </summary>
    public static class ArtifactWriter
    {
        public const int ChunkChars = 60000;

        public static string ClassName(int version) => "FounderPolicyV" + version.ToString(CultureInfo.InvariantCulture);
        public static string FileName(int version) => ClassName(version) + ".g.cs";

        public static string Write(ArtifactHeader h, QNet net)
        {
            h.NetShape = net.Shape.Text;
            h.WeightCount = net.W.Length;
            h.WeightsSha256 = net.WeightsSha256();
            var b64 = Convert.ToBase64String(net.WeightBytes());
            var sb = new StringBuilder();
            sb.Append("// <auto-generated>\n// Founder policy artifact written by DotNet/God.Train (god-train artifact, package UN6t). Do not edit.\n");
            sb.Append("// Status ").Append(h.Status).Append("; weights SHA-256 ").Append(h.WeightsSha256).Append("; thresholds SHA-256 ").Append(h.ThresholdsHash).Append(".\n// </auto-generated>\n");
            sb.Append("namespace God.Sim.Unified\n{\n");
            sb.Append("    /// <summary>Founder policy artifact v").Append(h.Version).Append(" (").Append(h.Status).Append("): header constants and int16 weights (base64, little-endian).</summary>\n");
            sb.Append("    public static class ").Append(ClassName(h.Version)).Append("\n    {\n");
            foreach (var f in ArtifactHeader.IntFields) sb.Append("        public const int ").Append(f).Append(" = ").Append(((int)typeof(ArtifactHeader).GetField(f).GetValue(h)).ToString(CultureInfo.InvariantCulture)).Append(";\n");
            foreach (var f in ArtifactHeader.StringFields) sb.Append("        public const string ").Append(f).Append(" = @\"").Append(((string)typeof(ArtifactHeader).GetField(f).GetValue(h)).Replace("\"", "\"\"")).Append("\";\n");
            int chunks = (b64.Length + ChunkChars - 1) / ChunkChars;
            sb.Append("        /// <summary>The weights' base64 in order (join the chunks).</summary>\n");
            sb.Append("        public static readonly string[] WeightsBase64 = { ");
            for (int i = 0; i < chunks; i++) sb.Append(i > 0 ? ", " : "").Append("Chunk").Append(i);
            sb.Append(" };\n");
            for (int i = 0; i < chunks; i++)
                sb.Append("        private const string Chunk").Append(i).Append(" = \"").Append(b64, i * ChunkChars, Math.Min(ChunkChars, b64.Length - i * ChunkChars)).Append("\";\n");
            sb.Append("    }\n}\n");
            return sb.ToString();
        }

        public static ArtifactHeader ParseHeader(string text, out short[] weights)
        {
            var h = new ArtifactHeader();
            foreach (var f in ArtifactHeader.IntFields)
            {
                var m = Regex.Match(text, @"public const int " + f + @" = (-?\d+);");
                if (!m.Success) throw new FormatException("artifact: missing " + f);
                typeof(ArtifactHeader).GetField(f).SetValue(h, int.Parse(m.Groups[1].Value, CultureInfo.InvariantCulture));
            }
            foreach (var f in ArtifactHeader.StringFields)
            {
                var m = Regex.Match(text, @"public const string " + f + " = @\"((?:[^\"]|\"\")*)\";");
                if (!m.Success) throw new FormatException("artifact: missing " + f);
                typeof(ArtifactHeader).GetField(f).SetValue(h, m.Groups[1].Value.Replace("\"\"", "\""));
            }
            var chunks = new SortedDictionary<int, string>();
            foreach (Match m in Regex.Matches(text, "private const string Chunk(\\d+) = \"([A-Za-z0-9+/=]*)\";"))
                chunks[int.Parse(m.Groups[1].Value, CultureInfo.InvariantCulture)] = m.Groups[2].Value;
            var b64 = new StringBuilder(); foreach (var kv in chunks) b64.Append(kv.Value);
            weights = QNet.FromBytes(Convert.FromBase64String(b64.ToString()));
            return h;
        }

        /// <summary>
        /// Null when the artifact may be loaded against the current schemas and catalogue; else the reason it is invalid (a changed
        /// <c>Obs</c>/<c>Act</c> schema hash, a different catalogue, a weight hash or count mismatch).
        /// </summary>
        public static string Verify(ArtifactHeader h, short[] weights, string catalogueHash)
        {
            if (h.ObsSchemaVersion != ObsSchema.Version || h.ObsSchemaHash != ObsSchema.SchemaHash) return "Obs schema changed";
            if (h.ActSchemaVersion != ActSchema.Version || h.ActSchemaHash != ActSchema.SchemaHash) return "Act schema changed";
            if (catalogueHash != null && h.CatalogueHash != catalogueHash) return "catalogue changed";
            if (weights.Length != h.WeightCount || Net.NetShape.Parse(h.NetShape).Count != weights.Length) return "weight count mismatch";
            if (new QNet(Net.NetShape.Parse(h.NetShape), weights).WeightsSha256() != h.WeightsSha256) return "weights hash mismatch";
            return null;
        }

        /// <summary>The catalogue content id the header records (UN3a's workbook SHA-256; "empty-catalogue" until UN3a merges).</summary>
        public static string CurrentCatalogueHash() => string.IsNullOrEmpty(Catalogue.WorkbookSha) ? "empty-catalogue" : Catalogue.WorkbookSha;
    }
}
